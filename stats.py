def get_statistics(player):
    """Summarize a player's session.

    Equity = cash bankroll + chips still on the table. Each roll's result is the
    change in equity, so chips that just sit on the table aren't counted as new action.
    """
    df = player.bet_history
    equity = [float(player.starting_bankroll)]
    if df is not None and len(df) > 0:
        equity += (df["bankroll"] + df["total_bets_in_play"]).to_list()
    equity.append(player.bankroll + player.chips_on_table())
    results = [b - a for a, b in zip(equity, equity[1:])]

    final_equity = equity[-1]
    net_result = final_equity - player.starting_bankroll
    wins = sum(r > 0 for r in results)
    losses = sum(r < 0 for r in results)
    return {
        'total_rolls': len(results),
        'rolls_won': wins,
        'rolls_lost': losses,
        'rolls_pushed': len(results) - wins - losses,
        'win_rate': wins / (wins + losses) if wins + losses else 0,
        'starting_bankroll': player.starting_bankroll,
        'final_bankroll': player.bankroll,
        'chips_on_table': player.chips_on_table(),
        'final_equity': final_equity,
        'min_equity': min(equity),
        'max_equity': max(equity),
        'net_result': net_result,
        'total_wagered': player.total_wagered,
        'total_returned': player.total_returned,
        'roi': net_result / player.starting_bankroll * 100 if player.starting_bankroll else 0,
        'loss_per_dollar_wagered': -net_result / player.total_wagered if player.total_wagered else 0,
    }
